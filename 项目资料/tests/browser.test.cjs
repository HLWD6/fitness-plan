"use strict";
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const { pathToFileURL } = require("node:url");
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || "/tmp/fitness-plan-tools/node_modules/playwright");
const P = require("../src/training.js");
const root = path.resolve(__dirname, "../..");
const url = pathToFileURL(path.join(root, "index.html")).href;
const examples = path.join(root, "项目资料/示例");

(async () => {
  const browser = await chromium.launch({ executablePath: "/usr/bin/google-chrome", headless: true, args: ["--no-sandbox"] });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, acceptDownloads: true });
  const old = { version: 8, records: [{ date: "2025-12-01", label: "卧推 A", plan: { weight: 100, sets: 4, reps: 9 }, actual: { weights: [100], reps: [9] } }], archives: [{ records: [{ date: "2025-11-01", label: "深蹲", plan: { weight: 90, sets: 5, reps: 5 }, actual: { weights: [90], reps: [5] } }] }] };
  const oldV9 = { version: 9, records: { 1: { day: 1, date: "2026-10-01", plan: { name: "卧推", weight: 115, sets: 4, reps: "9" }, actual: "115 kg，9 次", notes: "旧备注" } }, attempts: [], archives: [] };
  await context.addInitScript(({ legacy, previous }) => { localStorage.setItem("bench-rotation-v8", JSON.stringify(legacy)); localStorage.setItem("fitness-cycle-v9", JSON.stringify(previous)); }, { legacy: old, previous: oldV9 });
  const page = await context.newPage();
  const errors = [], requests = [];
  page.on("pageerror", (e) => errors.push(e.message));
  page.on("request", (req) => { if (/^https?:/.test(req.url())) requests.push(req.url()); });
  await page.goto(url);
  const read = () => page.evaluate(() => JSON.parse(localStorage.getItem("fitness-cycle-v10") || "null"));
  assert.equal(await page.locator("#tm").inputValue(), "167.5");
  assert.match(await page.locator("#sessionCard").innerText(), /DAY 09/);
  assert.match(await page.locator("#sessionCard").innerText(), /137.5 kg/);
  assert.equal(await page.locator("#benchIncrease").inputValue(), "5");
  assert.equal(await page.locator("#entryDay").inputValue(), "9");
  assert.match(await page.locator("#progressDenominator").innerText(), /30 次/);
  await page.locator("#tm").fill("170");
  await page.locator('#settingsForm button[type="submit"]').click();
  assert.deepEqual((await read()).config.benchWeights, [122.5, 130, 137.5, 145]);
  assert.match(await page.locator("#sessionCard").innerText(), /137.5 kg/);
  await page.locator("#seedBench").click();
  assert.equal(await page.locator("#bench0").inputValue(), "117.5");
  assert.deepEqual((await read()).config.benchWeights, [122.5, 130, 137.5, 145]);
  await page.reload();
  assert.equal(await page.locator("#bench0").inputValue(), "122.5");
  await page.locator("#tm").fill("167.5");
  await page.locator('#settingsForm button[type="submit"]').click();
  assert.match(await page.locator("#legacyNote").innerText(), /当前 1 条/);
  await page.locator("#legacyNote summary").first().click();
  assert.match(await page.locator("#legacyNote").innerText(), /卧推 A/);
  assert.match(await page.locator("#legacyNote").innerText(), /旧备注/);
  await page.locator('[data-round="3"]').click();
  assert.match(await page.locator('[data-day="47"]').innerText(), /165kg/);
  await page.locator('[data-day="47"]').click();
  assert.match(await page.locator("#sessionCard").innerText(), /165 kg/);
  assert.match(await page.locator("#sessionCard").innerText(), /硬拉/);
  await page.locator('[data-round="1"]').click();
  await page.locator('[data-day="1"]').click();

  const start = P.addDays(P.today(), -60);
  await page.locator("#startDate").fill(start);
  await page.locator("#rounds").selectOption("1");
  await page.locator("#entryDay").fill("1");
  await page.locator('#settingsForm button[type="submit"]').click();
  assert.match(await page.locator("#settingsStatus").innerText(), /已保存/);
  assert.equal((await read()).config.rounds, 1);
  assert.equal(await page.locator("#printSchedule tbody tr").count(), 16);
  await page.locator('select[name="triceps"]').selectOption({ label: "绳索臂屈伸" });
  await page.locator('#logForm [name="actual"]').fill('122.5 kg，9 / 9 / 9 / 9 <img src=x>');
  await page.locator('#logForm [name="date"]').fill(start);
  await page.locator('#logForm [name="result"]').selectOption("paused");
  await page.locator('#logForm button[type="submit"]').click();
  assert.equal((await read()).attempts.length, 1);
  assert.equal((await read()).records[1], undefined);
  assert.match(await page.locator("#sessionCard").innerText(), /DAY 01/);
  await page.locator('#logForm [name="date"]').fill(start);
  await page.locator('#logForm [name="result"]').selectOption("done");
  await page.locator('select[name="triceps"]').selectOption({ label: "绳索臂屈伸" });
  await page.locator('#logForm [name="actual"]').fill('122.5 kg，9 / 9 / 9 / 9 <img src=x>');
  await page.locator('#logForm button[type="submit"]').click();
  assert.equal((await read()).records[1].triceps, "绳索臂屈伸");
  assert.equal(await page.locator('#historyList img').count(), 0);
  assert.match(await page.locator("#sessionCard").innerText(), /DAY 02/);
  await page.locator('#logForm [name="date"]').fill(P.addDays(start, 1));
  await page.locator('#logForm button[type="submit"]').click();
  assert.match(await page.locator("#sessionCard").innerText(), /DAY 03/);
  await page.locator('#logForm [name="date"]').fill(P.addDays(start, 2));
  await page.locator('#logForm [name="result"]').selectOption("incomplete");
  await page.locator('#logForm button[type="submit"]').click();
  assert.match(await page.locator("#sessionCard").innerText(), /上次训练未完成/);
  assert.match(await page.locator("#sessionCard").innerText(), /DAY 05/);
  await page.locator("#squatOverride").fill("100");
  await page.locator('#settingsForm button[type="submit"]').click();
  assert.equal((await read()).squatOverrides[7], 100);
  assert.equal((await read()).records[3].plan.weight, 120);
  await page.locator('[data-day="7"]').click();
  assert.match(await page.locator("#sessionCard").innerText(), /100 kg/);
  assert.match(await page.locator("#sessionCard").innerText(), /硬拉/);
  assert.doesNotMatch(await page.locator("#sessionCard").innerText(), /腿屈伸/);
  await page.locator('[data-day="5"]').click();
  for (const day of [5,6,7,9,10,11,13,14,15]) {
    assert.match(await page.locator("#sessionCard").innerText(), new RegExp(`DAY ${String(day).padStart(2, "0")}`));
    await page.locator('#logForm [name="date"]').fill(P.addDays(start, day - 1));
    await page.locator('#logForm button[type="submit"]').click();
  }
  let state = await read();
  assert.equal(Object.keys(state.records).length, 12);
  assert.equal(state.records[7].plan.weight, 100);
  assert.equal(state.records[11].plan.weight, 105);
  assert.equal(state.records[15].plan.weight, 110);
  assert.equal(await page.locator("#cycleFinish").isVisible(), true);
  const minTest = await page.locator("#testDate").getAttribute("min");
  assert.equal(minTest, P.addDays(start, 21));
  await page.locator("#newTm").fill("175");
  await page.locator("#testDate").fill(minTest);
  await page.locator("#nextStart").fill(P.addDays(minTest, 1));
  await page.locator('#nextCycleForm button[type="submit"]').click();
  state = await read();
  assert.equal(state.config.tm, 175);
  assert.equal(state.config.squatStart, 115);
  assert.equal(Object.keys(state.records).length, 0);
  assert.equal(state.archives.length, 1);
  assert.equal(state.archives[0].test.tm, 175);
  assert.equal(state.archives[0].records[3].plan.weight, 120);
  assert.deepEqual(await page.evaluate(() => JSON.parse(localStorage.getItem("bench-rotation-v8"))), old);
  assert.deepEqual(await page.evaluate(() => JSON.parse(localStorage.getItem("fitness-cycle-v9"))), oldV9);
  const dlPromise = page.waitForEvent("download");
  await page.locator("#exportJson").click();
  const dl = await dlPromise;
  const exported = JSON.parse(fs.readFileSync(await dl.path(), "utf8"));
  assert.equal(exported.current.archives.length, 1);
  assert.deepEqual(exported.legacy["bench-rotation-v8"], old);
  assert.deepEqual(exported.legacy["fitness-cycle-v9"], oldV9);
  assert.deepEqual(errors, []);
  assert.deepEqual(requests, []);
  await context.close();

  // 用独立空白上下文更新参考图片、表格与打印示例，不读取个人记录。
  const blank = await browser.newContext({ viewport: { width: 1440, height: 1000 }, acceptDownloads: true });
  const preview = await blank.newPage();
  await preview.goto(url);
  await preview.screenshot({ path: path.join(examples, "界面预览.png") });
  const csvPromise = preview.waitForEvent("download");
  await preview.locator("#exportCsv").click();
  await (await csvPromise).saveAs(path.join(examples, "长期轮转训练表.csv"));
  await preview.emulateMedia({ media: "print" });
  assert.equal(await preview.locator("#printSchedule tbody tr").count(), 48);
  await preview.pdf({ path: path.join(examples, "长期轮转训练表.pdf"), format: "A4", landscape: true, printBackground: true });
  await blank.close();
  await browser.close();
  console.log("桌面：三层周期、可输入重量、暂停与未完成、日期、深蹲调整、旧数据、导出、周期归档和打印通过。");
})().catch((error) => { console.error(error); process.exit(1); });
