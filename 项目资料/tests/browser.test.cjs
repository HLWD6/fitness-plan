"use strict";
const assert = require("node:assert/strict"), path = require("node:path");
const { pathToFileURL } = require("node:url");
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || "/tmp/fitness-plan-tools/node_modules/playwright");
const P = require("../src/training.js");
const url = pathToFileURL(path.resolve(__dirname, "../../index.html")).href;
(async () => {
  const browser = await chromium.launch({ executablePath: "/usr/bin/google-chrome", headless: true });
  const config = P.defaults(P.addDays(P.today(), -30)), records = {};
  for (const day of P.plan(config)) if (day.type !== "rest") records[day.day] = { day: day.day, date: day.date, plan: day, result: "done", actualWeight: null };
  const completed = await browser.newContext();
  await completed.addInitScript(state => localStorage.setItem("fitness-cycle-v15", JSON.stringify(state)), { version: 15, config, records, attempts: [], archives: [], drafts: {} });
  const done = await completed.newPage();
  await done.goto(url);
  assert.equal(await done.locator("#cycleFinish").isVisible(), true);
  const nextDate = P.addDays(P.plan(config).at(-1).date, 6);
  assert.equal(await done.locator("#nextStart").inputValue(), nextDate);
  await done.locator("#nextCycleForm button").click();
  const restarted = await done.evaluate(() => JSON.parse(localStorage.getItem("fitness-cycle-v15")));
  assert.equal(restarted.config.startDate, nextDate);
  assert.equal(restarted.archives.length, 1);
  assert.equal(Object.keys(restarted.records).length, 0);
  await completed.close();

  const previous = { version: 14, config: { tm: 160, tm2: 170, startDate: P.addDays(P.today(), -10) }, records: { 1: { day: 1, date: P.addDays(P.today(), -10), plan: { name: "卧推", weight: 120, sets: 5, reps: "8" }, result: "done", actual: "历史训练" } }, attempts: [], archives: [], drafts: {} };
  const migrated = await browser.newContext();
  await migrated.addInitScript(state => localStorage.setItem("fitness-cycle-v14", JSON.stringify(state)), previous);
  const page = await migrated.newPage(), errors = [];
  page.on("pageerror", error => errors.push(error.message));
  await page.goto(url);
  const state = await page.evaluate(() => JSON.parse(localStorage.getItem("fitness-cycle-v15")));
  assert.equal(state.records[1].actualWeight, 120);
  assert.deepEqual(state.archives[0].records, previous.records);
  assert.equal(await page.locator("#workout").isVisible(), false);
  assert.doesNotMatch(await page.locator("#planCalendar").innerText(), /温宁|热身/);
  for (const [day, name, weight, accessory] of [[1, "快速卧推", 120, "实力推"], [5, "停顿卧推", 135, "自重臂屈伸"], [9, "赛推", 150, "俯卧撑"], [13, "无腿卧推", 100, ""]]) {
    const cell = page.locator(`[data-day="${day}"]`);
    assert.match(await cell.innerText(), new RegExp(name));
    if (accessory) assert.match(await cell.innerText(), new RegExp(accessory));
    await cell.click();
    assert.equal(await page.locator("#workout").isVisible(), true);
    assert.match(await page.locator("#sessionCard").innerText(), new RegExp(`参考约 ${weight} kg`));
    assert.doesNotMatch(await page.locator("#sessionCard").innerText(), /温宁|热身/);
    await page.keyboard.press("Escape");
    assert.equal(await page.locator("#workout").isVisible(), false);
  }
  assert.deepEqual(errors, []);
  await migrated.close();

  const logging = await browser.newContext();
  const logConfig = P.defaults(P.addDays(P.today(), -1));
  await logging.addInitScript(state => localStorage.setItem("fitness-cycle-v15", JSON.stringify(state)), { version: 15, config: logConfig, records: { 1: { day: 1, date: logConfig.startDate, result: "done", plan: P.plan(logConfig)[0], actualWeight: 120 } }, attempts: [], archives: [], drafts: {} });
  const log = await logging.newPage();
  await log.goto(url);
  await log.locator('[data-day="2"]').click();
  await log.locator('[name="actual"]').fill("3×6，动作稳定");
  await log.locator("#logForm button[type=submit]").click();
  assert.equal(await log.locator("#workout").isVisible(), false);
  assert.equal(await log.locator('[data-day="2"]').evaluate(element => element.classList.contains("completed")), true);
  assert.equal(await log.locator('[data-day="3"]').evaluate(element => element.classList.contains("upcoming")), true);
  const recorded = await log.evaluate(() => JSON.parse(localStorage.getItem("fitness-cycle-v15")));
  assert.equal(recorded.records[2].actual, "3×6，动作稳定");
  await logging.close();
  await browser.close();
  console.log("日历、辅助动作、记录弹窗、保存与归档正常。");
})().catch(error => { console.error(error); process.exit(1); });
