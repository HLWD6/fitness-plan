"use strict";
const assert = require("node:assert/strict"), path = require("node:path"), { pathToFileURL } = require("node:url");
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || "/tmp/fitness-plan-tools/node_modules/playwright");
const P = require("../src/training.js"), url = pathToFileURL(path.resolve(__dirname, "../../index.html")).href, KEY = "fitness-templates-v17";
(async () => {
  const browser = await chromium.launch({ executablePath: "/usr/bin/google-chrome", headless: true });
  const context = await browser.newContext({ acceptDownloads: true }), page = await context.newPage(), errors = [];
  page.on("pageerror", error => errors.push(error.message));
  await page.goto(url);
  assert.equal(await page.locator(".calendar-cell").count(), 7);
  assert.equal(await page.locator("#planCalendar time").count(), 0);
  await page.locator("#historyLink").click();
  assert.match(await page.locator(".month-toolbar strong").innerText(), /2026年11月/);
  assert.equal(await page.locator(".record-day").count(), 30);
  const empty = page.locator('[data-log-date="2026-11-10"]');
  assert.equal(await empty.evaluate(e => e.classList.contains("has-records")), false);
  await empty.click(); assert.equal(await page.locator("#historyList").innerText(), "");
  await page.locator("#recordSelectedDay").click();
  assert.equal(await page.locator('[name="date"]').inputValue(), "2026-11-10");
  assert.equal(await page.locator('[name="templateId"] option[value="rest"]').count(), 0);
  await page.keyboard.press("Escape");
  await page.locator('[data-month-step="-1"]').click(); assert.match(await page.locator(".month-toolbar strong").innerText(), /2026年10月/);
  await page.locator('[data-month-step="1"]').click();
  await page.locator('[data-log-date="2026-11-11"]').click();
  assert.match(await page.locator("#historyList").innerText(), /深蹲 A/);
  await page.locator('[data-record="confirmed-2026-11-11-squat-a"]').click();
  assert.deepEqual(await page.locator(".weight-grid input").evaluateAll(inputs => inputs.map(x => Number(x.value))), [120, 120, 120, 120, 120]);
  await page.locator('[name="weight-0"]').fill("122.5"); await page.locator("#logForm button[type=submit]").click();
  await page.reload(); await page.locator("#historyLink").click();
  let state = await page.evaluate(key => JSON.parse(localStorage.getItem(key)), KEY);
  assert.equal(state.records.find(r => r.templateId === "squat-a").setWeights[0], 122.5);
  await page.locator('[data-log-date="2026-11-12"]').click();
  await page.locator('[data-record="confirmed-2026-11-12-bench-b"]').click();
  assert.deepEqual(await page.locator(".weight-grid input").evaluateAll(inputs => inputs.map(x => Number(x.value))), [120, 125, 125, 130, 130]);
  assert.match(await page.locator(".record-main").innerText(), /参考 135 kg/);
  await page.keyboard.press("Escape");
  await page.locator('[data-template="bench-a"]').click();
  await page.locator('[name="date"]').fill("2026-11-06");
  assert.ok((await page.locator(".weight-grid input").evaluateAll(inputs => inputs.map(x => x.value))).every(x => x === ""));
  for (let i = 0; i < 5; i++) await page.locator(`[name="weight-${i}"]`).fill(String(110 + i * 2.5));
  await page.locator("#logForm button[type=submit]").click();
  assert.equal(await page.locator("#workout").isVisible(), false);
  assert.equal(await page.locator('[data-log-date="2026-11-06"]').evaluate(e => e.classList.contains("has-records")), true);
  state = await page.evaluate(key => JSON.parse(localStorage.getItem(key)), KEY);
  assert.deepEqual(state.records.find(x => x.date === "2026-11-06").setWeights, [110, 112.5, 115, 117.5, 120]);
  assert.equal(state.records.find(x => x.date === "2026-11-06").snapshot.main.referenceWeight, 120);
  await page.locator("#openWorkout").click();
  await page.locator('[name="date"]').fill("2026-11-05");
  await page.locator('[name="templateId"]').selectOption("bench-d");
  await page.locator("#logForm button[type=submit]").click();
  state = await page.evaluate(key => JSON.parse(localStorage.getItem(key)), KEY);
  assert.ok(state.records.find(x => x.date === "2026-11-05").setWeights.every(x => x === null));
  const count = state.records.length;
  await page.locator('[data-log-date="2026-11-12"]').click();
  await page.locator('[data-record="confirmed-2026-11-12-bench-b"]').click();
  await page.locator('[name="weight-3"]').fill("132.5"); await page.locator("#logForm button[type=submit]").click();
  await page.reload(); state = await page.evaluate(key => JSON.parse(localStorage.getItem(key)), KEY);
  assert.equal(state.records.length, count); assert.ok(state.records.every(r => r.templateId !== "rest"));
  assert.deepEqual(state.records.find(x => x.id === "confirmed-2026-11-12-bench-b").setWeights, [120, 125, 125, 132.5, 130]);
  await page.locator("#historyLink").click();
  const exported = page.waitForEvent("download"); await page.locator("#exportCsv").click();
  const download = await exported, fs = require("node:fs"), csv = fs.readFileSync(await download.path(), "utf8");
  assert.match(csv, /"120","125","125","132.5","130"/); assert.doesNotMatch(csv, /休息/);
  assert.deepEqual(errors, []); await context.close();

  const previous = { version: 16, records: [...P.seedRecords().map(r => r.templateId === "squat-a" ? { ...r, setWeights: Array(5).fill(null) } : r), { id: "rest", date: "2026-11-10", templateId: "rest", setWeights: [] }] };
  previous.draft = { recordId: null, templateId: "bench-c", date: "2026-11-10", setWeights: [140, 140, 140, 140, 140], result: "done", notes: "草稿", triceps: "" };
  const migrated = await browser.newContext();
  await migrated.addInitScript(x => localStorage.setItem("fitness-templates-v16", JSON.stringify(x)), previous);
  const old = await migrated.newPage(); await old.goto(url);
  const result = await old.evaluate(key => ({ current: JSON.parse(localStorage.getItem(key)), old: JSON.parse(localStorage.getItem("fitness-templates-v16")) }), KEY);
  assert.deepEqual(result.old, previous); assert.deepEqual(result.current.draft, previous.draft); assert.equal(result.current.records.length, 3);
  assert.deepEqual(result.current.records.find(r => r.templateId === "squat-a").setWeights, [120, 120, 120, 120, 120]);
  assert.ok(result.current.records.every(r => r.templateId !== "rest"));
  await migrated.close(); await browser.close();
  console.log("月历、空白休息日、深蹲120kg、逐组编辑、迁移与导出正常。");
})().catch(error => { console.error(error); process.exit(1); });
