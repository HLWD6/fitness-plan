"use strict";
const assert = require("node:assert/strict"), path = require("node:path"), { pathToFileURL } = require("node:url");
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || "/tmp/fitness-plan-tools/node_modules/playwright");
const P = require("../src/training.js"), url = pathToFileURL(path.resolve(__dirname, "../../index.html")).href, KEY = "fitness-templates-v16";
(async () => {
  const browser = await chromium.launch({ executablePath: "/usr/bin/google-chrome", headless: true });
  const context = await browser.newContext({ acceptDownloads: true }), page = await context.newPage(), errors = [];
  page.on("pageerror", error => errors.push(error.message));
  await page.goto(url);
  assert.equal(await page.locator(".calendar-cell").count(), 7);
  assert.equal(await page.locator("#planCalendar time").count(), 0);
  assert.equal(await page.locator('[data-template="rest"]').count(), 0);
  assert.doesNotMatch(await page.locator("#planCalendar").innerText(), /温宁|热身|下一次|第\d+天/);
  let state = await page.evaluate(key => JSON.parse(localStorage.getItem(key)), KEY);
  assert.deepEqual(state.records.map(x => [x.date, x.templateId]), P.seedRecords().map(x => [x.date, x.templateId]));
  await page.locator("#historyLink").click();
  await page.locator('[data-record="confirmed-2026-11-12-bench-b"]').click();
  assert.deepEqual(await page.locator(".weight-grid input").evaluateAll(inputs => inputs.map(x => Number(x.value))), [120, 125, 125, 130, 130]);
  assert.match(await page.locator(".record-main").innerText(), /参考 135 kg/);
  await page.keyboard.press("Escape");
  await page.locator('[data-template="bench-a"]').click();
  await page.locator('[name="date"]').fill("2026-11-06");
  assert.ok((await page.locator(".weight-grid input").evaluateAll(inputs => inputs.map(x => x.value))).every(x => x === ""));
  for (let i = 0; i < 5; i++) await page.locator(`[name="weight-${i}"]`).fill(String(110 + i * 2.5));
  await page.locator("#logForm button[type=submit]").click();
  assert.equal(await page.locator("#workout").isVisible(), false);
  state = await page.evaluate(key => JSON.parse(localStorage.getItem(key)), KEY);
  assert.deepEqual(state.records.find(x => x.date === "2026-11-06").setWeights, [110, 112.5, 115, 117.5, 120]);
  assert.equal(state.records.find(x => x.date === "2026-11-06").snapshot.main.referenceWeight, 120);
  await page.locator("#openWorkout").click();
  await page.locator('[name="date"]').fill("2026-11-07");
  await page.locator('[name="templateId"]').selectOption("rest");
  assert.equal(await page.locator(".weight-grid").count(), 0);
  await page.locator("#logForm button[type=submit]").click();
  await page.locator("#openWorkout").click();
  await page.locator('[name="date"]').fill("2026-11-05");
  await page.locator('[name="templateId"]').selectOption("bench-d");
  await page.locator("#logForm button[type=submit]").click();
  state = await page.evaluate(key => JSON.parse(localStorage.getItem(key)), KEY);
  assert.ok(state.records.find(x => x.date === "2026-11-05").setWeights.every(x => x === null));
  const count = state.records.length;
  await page.locator('[data-record="confirmed-2026-11-12-bench-b"]').click();
  await page.locator('[name="weight-3"]').fill("132.5");
  await page.locator("#logForm button[type=submit]").click();
  await page.reload();
  state = await page.evaluate(key => JSON.parse(localStorage.getItem(key)), KEY);
  assert.equal(state.records.length, count);
  assert.deepEqual(state.records.find(x => x.id === "confirmed-2026-11-12-bench-b").setWeights, [120, 125, 125, 132.5, 130]);
  assert.equal(state.records.find(x => x.id === "confirmed-2026-11-12-bench-b").snapshot.main.referenceWeight, 135);
  await page.locator("#historyLink").click();
  const exported = page.waitForEvent("download");
  await page.locator("#exportCsv").click();
  const download = await exported, fs = require("node:fs");
  const csv = fs.readFileSync(await download.path(), "utf8");
  assert.match(csv, /第5组kg/); assert.match(csv, /"120","125","125","132.5","130"/);
  assert.deepEqual(errors, []);
  await context.close();

  const previous = { version: 15, records: { 1: { day: 1, date: "2026-11-12", plan: { type: "chest", micro: 1 }, actualWeight: 120 }, 2: { day: 2, date: "2026-11-08", plan: { type: "back" }, result: "done", notes: "旧记录" } }, attempts: [], archives: [] };
  const migrated = await browser.newContext();
  await migrated.addInitScript(x => localStorage.setItem("fitness-cycle-v15", JSON.stringify(x)), previous);
  const old = await migrated.newPage(); await old.goto(url);
  const result = await old.evaluate(key => ({ current: JSON.parse(localStorage.getItem(key)), old: JSON.parse(localStorage.getItem("fitness-cycle-v15")) }), KEY);
  assert.deepEqual(result.old, previous);
  assert.equal(result.current.records.length, 5);
  assert.deepEqual(result.current.records.filter(x => x.date === "2026-11-12").map(x => x.templateId), ["bench-b"]);
  await migrated.close(); await browser.close();
  console.log("固定模板、自由日期、逐组实重、重复训练、编辑和旧数据迁移正常。");
})().catch(error => { console.error(error); process.exit(1); });
